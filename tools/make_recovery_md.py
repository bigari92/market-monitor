"""Generate docs/RECOVERY.md from the recovered scripts themselves.

Written as a generator rather than by hand so the inventory cannot drift from the files, and so
the pipeline ORDER is taken from the transcript (the order each script was first written) instead
of guessed from filenames.

Run:  C:/Users/valer/.venvs/market-monitor/Scripts/python.exe tools/make_recovery_md.py
"""
from __future__ import annotations

import ast
import json
import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
RECOVERED = REPO / "recovered"
OUT = REPO / "docs" / "RECOVERY.md"
TRANSCRIPT = pathlib.Path(
    "C:/Users/valer/.claude/projects/C--Users-valer-Investing/"
    "a65146b1-c1e6-4733-aea1-2152de4aaabb.jsonl"
)

DATA_RE = re.compile(r"""['"]([\w./\\-]+\.(?:parquet|csv))['"]""")

# Recovered from the same transcript, deliberately kept OUT of this repository.
# Recorded here so the reason survives a regeneration and nobody re-adds it.
EXCLUDED = {
    "fix_tax_language.py": (
        "embeds verbatim passages of the owner's private plan.md (sleeve sizes, "
        "contributions, declaration wording). Not pipeline code. Kept at "
        "C:/Users/valer/Investing/fix_tax_language.py, outside any repository."
    ),
}


def transcript_order() -> dict[str, int]:
    """Map script name -> index of the Bash call that first wrote it. Empty if unavailable."""
    if not TRANSCRIPT.is_file():
        return {}
    order: dict[str, int] = {}
    step = 0
    with TRANSCRIPT.open(encoding="utf-8") as fh:
        for line in fh:
            try:
                row = json.loads(line)
            except ValueError:
                continue
            content = row.get("message", {}).get("content")
            if not isinstance(content, list):
                continue
            for block in content:
                if not (isinstance(block, dict) and block.get("type") == "tool_use"):
                    continue
                payload = block.get("input") or {}
                text = str(payload.get("command", "")) + str(payload.get("file_path", ""))
                if not text:
                    continue
                step += 1
                for name in re.findall(r"([\w-]+\.py)", text):
                    order.setdefault(name, step)
    return order


def describe(path: pathlib.Path) -> dict:
    source = path.read_text(encoding="utf-8")
    try:
        tree = ast.parse(source, filename=str(path))
        doc = (ast.get_docstring(tree) or "").strip()
        funcs = [n.name for n in tree.body if isinstance(n, ast.FunctionDef)]
    except SyntaxError:
        doc, funcs = "", []
    summary = doc.splitlines()[0].strip() if doc else "(no docstring)"
    artefacts = sorted({m for m in DATA_RE.findall(source)})
    return {
        "name": path.name,
        "bytes": len(source),
        "summary": summary,
        "funcs": funcs,
        "artefacts": [a.replace("\\", "/").split("/")[-1] for a in artefacts],
    }


def main() -> int:
    if not RECOVERED.is_dir():
        print(f"missing {RECOVERED}", file=sys.stderr)
        return 1

    order = transcript_order()
    items = [describe(p) for p in sorted(RECOVERED.glob("*.py"))]
    items.sort(key=lambda d: (order.get(d["name"], 10**6), d["name"]))

    lines: list[str] = []
    add = lines.append
    add("# RECOVERY — the Sept-2026 research pipeline\n")
    add("**Generated by `tools/make_recovery_md.py`. Do not hand-edit; re-run it.**\n")
    add(
        "The pipeline that produced the published result "
        "(`https://claude.ai/code/artifact/b29e52c8-d152-4ce6-a631-06e9d575ea01`) lived in a "
        "session scratch directory that has since been deleted. The session transcript retained "
        "the scripts as shell heredocs, and `tools/extract_from_transcript.py` pulls them back "
        "out deterministically.\n"
    )
    add(
        f"Recovered: **{len(items)} scripts, "
        f"{sum(i['bytes'] for i in items):,} characters**, all compiling on Python 3.14 "
        "(`tests/test_recovered_compiles.py`).\n"
    )
    add("## Code recovered is not result validated\n")
    add(
        "Re-running these scripts reproduces the published numbers *and the flaws that produced "
        "them*. Four defects are known before a single line is re-run:\n"
    )
    add(
        "1. **Survivorship.** `build_universe.py` fetches the NASDAQ Trader symbol directory "
        "**live**, so the universe is today's listings only. Delisted companies are absent, "
        "which is exactly where a cheapness signal's apparent edge hides. This is structural.\n"
        "2. **Corporate actions are invisible.** `download_prices.py` passes "
        "`auto_adjust=True`, after which a price move and a split cannot be told apart.\n"
        "3. **Overlapping observations.** 12-month forward returns on a monthly rebalance grid: "
        "127 observations that share 11/12ths of their window, so every naive t-statistic is "
        "inflated. The honest effective sample is ~10 independent years, not 270,392 rows.\n"
        "4. **No cost model.** Nothing deducts commission, spread or tax anywhere.\n"
    )
    add(
        "A fifth item is a question, not a defect: `pct_of_52w_high` and `max_dd_12m` were "
        "described in a design review as the same quantity. Reading `factors.py` they are not — "
        "one is today's price over the 252-day maximum, the other the deepest trough relative to "
        "its own running maximum anywhere in the window. Measure their correlation before "
        "collapsing them.\n"
    )
    if EXCLUDED:
        add("## Recovered but deliberately not in this repository\n")
        for name, reason in sorted(EXCLUDED.items()):
            add(f"- `{name}` — {reason}")
        add(
            "\n`tools/extract_from_transcript.py` will regenerate these from the transcript. "
            "`.gitignore` and `tools/githooks/pre-commit` stop them being committed again.\n"
        )

    add("## Inventory, in the order the scripts were written\n")
    add("| # | script | chars | what it does |")
    add("|---|---|---|---|")
    for i, item in enumerate(items, 1):
        summary = item["summary"].replace("|", "/")
        if len(summary) > 115:
            summary = summary[:112] + "..."
        add(f"| {i} | `{item['name']}` | {item['bytes']:,} | {summary} |")
    add("")
    add("## Artefacts each script touches\n")
    add("Useful for reconstructing the dependency order: a script that reads `panel.parquet` "
        "runs after whatever wrote it.\n")
    for item in items:
        if item["artefacts"]:
            add(f"- `{item['name']}` — " + ", ".join(f"`{a}`" for a in item["artefacts"]))
    add("")
    add("## Functions defined\n")
    for item in items:
        if item["funcs"]:
            add(f"- `{item['name']}` — " + ", ".join(f"`{f}()`" for f in item["funcs"]))
    add("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(REPO).as_posix()} — {len(items)} scripts")
    if not order:
        print("NOTE: transcript unavailable, inventory is alphabetical not chronological")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
